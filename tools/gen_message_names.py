"""Generate cs2_gc/message_names.inc (GC message id -> name) from protobufs/*.proto.

    python tools/gen_message_names.py

Rerun after dumping new protos with tools/dump_protos.py.
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROTO_DIR = os.path.join(ROOT, "protobufs")
OUT = os.path.join(ROOT, "cs2_gc", "message_names.inc")


def main():
    names = {}
    for fn in sorted(os.listdir(PROTO_DIR)):
        if not fn.endswith(".proto"):
            continue
        text = open(os.path.join(PROTO_DIR, fn), encoding="utf-8").read()
        for enum in re.finditer(r"^enum (\w+) \{(.*?)^\}", text, re.S | re.M):
            for name, value in re.findall(r"^\s*(k_E(?:SO)?Msg\w*)\s*=\s*(-?\d+);", enum.group(2), re.M):
                value = int(value)
                if value < 0:
                    continue
                names.setdefault(value, name)

    lines = ["// Generated by tools/gen_message_names.py from protobufs/*.proto, do not edit.",
             "// { message id, name }, sorted by id"]
    for value in sorted(names):
        lines.append(f'{{ {value}, "{names[value]}" }},')
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{len(names)} message names -> {OUT}")


if __name__ == "__main__":
    main()
