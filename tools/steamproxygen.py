"""Generate a csgo_gc style proxy header from an old Steam interface header.

    python tools/steamproxygen.py steamworks/sdk/public/steam_old/isteamclient023.h \
        SteamClient 023 > steamworks/sdk/public/proxy/steamclientproxy023.h

Every virtual method of I<Name><Version> gets an override that forwards to the
original interface, unless the proxy class (<Name>Proxy) has a PROXY_FUNC with
a matching signature, in which case that one is called with the original as
the first argument. Same output format as the generated headers that came with
csgo_gc.
"""
import re
import sys


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def split_args(arglist):
    args, depth, cur = [], 0, ""
    for ch in arglist:
        if ch in "(<":
            depth += 1
        elif ch in ")>":
            depth -= 1
        if ch == "," and depth == 0:
            args.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        args.append(cur.strip())
    return [a for a in args if a and a != "void"]


def strip_default(arg):
    depth = 0
    for i, ch in enumerate(arg):
        if ch in "(<":
            depth += 1
        elif ch in ")>":
            depth -= 1
        elif ch == "=" and depth == 0:
            return arg[:i].strip()
    return arg.strip()


def arg_name(arg, index):
    arg = re.sub(r"STEAM_\w+\([^)]*\)", "", arg).strip()
    m = re.search(r"([A-Za-z_]\w*)\s*(\[[^\]]*\])?$", arg)
    if not m or re.fullmatch(r"(const\s+)?\w+\s*[*&]*", arg) and " " not in arg.replace("const ", ""):
        return None
    return m.group(1)


def parse_methods(text, cls):
    text = strip_comments(text)
    body = text[text.index("class " + cls):]
    body = body[body.index("{") + 1:]
    # unwrap STEAM_PRIVATE_API( ... ) so private methods get proxied too
    body = re.sub(r"STEAM_PRIVATE_API\s*\(\s*(virtual[^;]*;)\s*\)", r"\1", body)
    methods = []
    for m in re.finditer(r"virtual\s+([^;{}]*?)\b(\w+)\s*\(([^;]*?)\)\s*(const)?\s*=\s*0\s*;", body, re.S):
        ret = " ".join(m.group(1).split())
        name = m.group(2)
        args = [" ".join(strip_default(a).split()) for a in split_args(m.group(3))]
        methods.append((ret, name, args, bool(m.group(4))))
    return methods


def main():
    path, base, version = sys.argv[1], sys.argv[2], sys.argv[3]
    iface = f"I{base}{version}"
    proxy = f"{base}Proxy{version}"
    owner = f"{base}Proxy"
    include = path.replace("\\", "/").split("public/")[-1]
    with open(path, encoding="utf-8") as f:
        methods = parse_methods(f.read(), iface)

    guard = f"{base.upper()}PROXY{version}_H"
    out = [
        "// Automatically generated by tools/steamproxygen.py, do not modify!!!",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        '#include "steamproxy.h"',
        f"#include <{include}>",
        "",
        f"class {proxy} final : public {iface}",
        "{",
        f"    {iface} *m_original;",
        f"    {owner} *m_proxy;",
        "",
        "public:",
        f"    {proxy}({iface} *original, {owner} *proxy)",
        "        : m_original{ original }",
        "        , m_proxy{ proxy }",
        "    {",
        "    }",
    ]
    for ret, name, args, const in methods:
        names = []
        decl = []
        for i, a in enumerate(args):
            # drop STEAM_ARRAY_COUNT(...) style annotations
            a = " ".join(re.sub(r"\bSTEAM_[A-Z_]+\s*\([^()]*\)", "", a).split())
            n = arg_name(a, i)
            if n is None or "(*)" in a:
                n = f"a{i}"
                a = f"TypeIdentityT<{a}> {n}" if "(*)" in a else f"{a} {n}"
            names.append(n)
            decl.append(a)
        call = ", ".join(names)
        pcall = ", ".join(["o"] + names)
        sig = f"{ret}{name}" if ret.endswith(("*", "&")) else f"{ret} {name}"
        pmf = f"&{iface}::{name}"
        if sum(1 for m in methods if m[1] == name) > 1:
            # overloaded: pick the right one explicitly
            types = []
            for d, n in zip(decl, names):
                t = d[: d.rfind(n)].strip() if not d.startswith("TypeIdentityT<") else d[len("TypeIdentityT<"): d.rfind(">")]
                types.append(t)
            pmf = f"static_cast<{ret} ({iface}::*)({', '.join(types)}){' const' if const else ''}>({pmf})"
        out += [
            "",
            f"    {sig}({', '.join(decl)}){' const' if const else ''} override",
            "    {",
            f"        return [&](auto p) -> {ret}",
            "        {",
            f"            auto o = MakeOrig<{pmf}>(m_original);",
            f"            if constexpr (requires {{ p->{name}({pcall}); }})",
            f"                return p->{name}({pcall});",
            "            else",
            f"                return o({call});",
            "        }(m_proxy);",
            "    }",
        ]
    out += ["};", "", f"#endif // {guard}", ""]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
